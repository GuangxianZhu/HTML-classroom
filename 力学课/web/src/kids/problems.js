// 启蒙篇的练习题：每小课 4 个出题函数，r 是随机数（mech.js 的 rng）。返回 { q, opts, ans, why, val? }。
// 只用小学数学：数字是整数、能口算，不出现负数运算和字母。错误选项按孩子常犯的错算出来，讲解里点破。
// test_mech.mjs 每个函数跑 400 遍，查选项、答案和“能口算”。

const pick4 = (right, wrongs, fill) => {
  const out = [right];
  for (const w of [...wrongs, ...fill]) { if (!out.includes(w)) out.push(w); if (out.length === 4) break; }
  return out;
};

export const KGEN = {
  4: [
    (r) => { // 数照片：从第 0 秒拍到第 n 秒（栅栏问题）
      const n = r.int(4, 12);
      const opts = pick4(`${n + 1} 张`, [`${n} 张`, `${n - 1} 张`, `${n * 2} 张`], [`${n + 2} 张`]);
      return { q: `每秒拍一张照片，从第 0 秒一直拍到第 ${n} 秒。一共几张？`, opts, ans: 0, val: n + 1,
        why: `第 0 秒也要拍一张。0、1、2……一直数到 ${n}，一共 ${n + 1} 张。` };
    },
    (r) => { // 两张照片位置一样
      const a = r.step(10, 50, 10), k = r.int(1, 6);
      const opts = [`停着`, `往东开了 ${a} 米`, `开回了家`, `在开上坡`];
      return { q: `第 ${k} 秒的照片里，车在东 ${a} 米。第 ${k + 1} 秒的照片里，车还在东 ${a} 米。这一秒车最可能在干什么？`, opts, ans: 0,
        why: `两张照片里车在同一个地方，这一秒位置没有变，所以是停着。图上这一段是平的。` };
    },
    (r) => { // 从图上读出挪了多少
      const t1 = r.int(1, 3), t2 = t1 + r.int(2, 4), a = r.step(10, 30, 10), b = a + r.step(10, 30, 10);
      const d = b - a;
      const opts = pick4(`往东开了 ${d} 米`, [`往东开了 ${b} 米`, `往东开了 ${a + b} 米`, `往西开了 ${d} 米`], [`往东开了 ${d * 2} 米`]);
      return { q: `位置-时间图上，第 ${t1} 秒的点在东 ${a} 米，第 ${t2} 秒的点在东 ${b} 米。这几秒车往哪边、开了多少米？`, opts, ans: 0, val: d,
        why: `点往上走，车在往东开。从东 ${a} 米到东 ${b} 米，挪了 ${b} − ${a} = ${d} 米。${b} 米是车在哪，不是开了多少。` };
    },
    (r) => { // 线往下 = 往回开（不是下坡、不是减速）
      const k = r.pick(['往下斜', '一直往下走']);
      const opts = [`在往西开（往回开）`, `在下坡`, `在慢慢停下来`, `停着`];
      return { q: `位置-时间图上，有一段线${k}。那几秒车在干什么？`, opts, ans: 0,
        why: `越往上越靠东，线往下走，就是车越来越靠西，也就是在往回开。图的样子不是路的样子，和上坡下坡没关系。` };
    },
  ],
  6: [
    (r) => { // 速度 = 米数 ÷ 秒数
      const v = r.int(2, 9), t = r.int(2, 6), d = v * t;
      const opts = pick4(`每秒 ${v} 米`, [`每秒 ${d * t} 米`, `每秒 ${d + t} 米`, `每秒 ${d - t} 米`], [`每秒 ${v + 1} 米`, `每秒 ${v * 2} 米`]);
      return { q: `小明 ${t} 秒走了 ${d} 米，走得一样快。他的速度是多少？`, opts, ans: 0, val: v,
        why: `速度是每秒走几米：${d} ÷ ${t} = ${v}，每秒 ${v} 米。不是乘，${t} 秒把 ${d} 米平分成了 ${t} 份。` };
    },
    (r) => { // 同时出发，几秒后领先多少
      const a = r.int(8, 15), b = r.int(3, a - 2), t = r.int(2, 5), d = (a - b) * t;
      const opts = pick4(`${d} 米`, [`${a * t} 米`, `${a - b} 米`, `${b * t} 米`], [`${d + 5} 米`]);
      return { q: `红车每秒 ${a} 米，紫车每秒 ${b} 米，一起从家门口往东开。${t} 秒后红车领先几米？`, opts, ans: 0, val: d,
        why: `红车每秒比紫车多走 ${a} − ${b} = ${a - b} 米，${t} 秒多走 ${a - b} × ${t} = ${d} 米。` };
    },
    (r) => { // 高的线不一定快
      const sw = r.next() < .5;
      const A = sw ? '红车' : '紫车', Bn = sw ? '紫车' : '红车';
      const opts = [`${Bn}，它的线更陡`, `${A}，它的线更高`, `一样快`, `看不出来`];
      return { q: `位置-时间图上，${A}的线又高又平，${Bn}的线低但是很陡。这一会儿谁快？`, opts, ans: 0,
        why: `线高只说明车靠东（离家远），不说明快。线陡，是每秒往上走得多，也就是每秒走的米数多。${Bn}快。` };
    },
    (r) => { // 追上要几秒
      const diff = r.int(2, 6), t = r.int(2, 6), head = diff * t;
      const opts = pick4(`${t} 秒`, [`${head * diff} 秒`, `${head + diff} 秒`, `${head - diff} 秒`], [`${t + 1} 秒`, `${t * 2} 秒`]);
      return { q: `紫车在红车前面 ${head} 米。红车每秒比紫车多走 ${diff} 米。红车几秒能追上？`, opts, ans: 0, val: t,
        why: `每过一秒，差距少 ${diff} 米。${head} 米要少几次？${head} ÷ ${diff} = ${t}，${t} 秒追上。` };
    },
  ],
};
